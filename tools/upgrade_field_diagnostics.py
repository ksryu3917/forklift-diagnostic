def choose(system,symptom,cause,c):
    if system=='트랜스미션': return transmission_override(symptom,cause,c)
    if system=='에어컨': return ac_override(symptom,cause,c)
    if system=='주차 브레이크': return parking_override(symptom,cause,c)
    if system=='브레이크': return brake_override(symptom,cause,c)
    if system=='스티어링': return steering_override(symptom,cause,c)
    if system=='유압': return hydraulic_override(symptom,cause,c)
    if system=='마스트': return mast_override(symptom,cause,c)
    if system=='드라이브 액슬': return axle_override(symptom,cause,c)
    return work_override(system,symptom,cause,c)


