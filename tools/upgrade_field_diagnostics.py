def main():
    db=json.loads(DB_PATH.read_text(encoding='utf-8'))
    tm=json.loads(TM_PATH.read_text(encoding='utf-8'))

    changed=0
    bysys=Counter()
    for s in db.get('symptoms',[]):
        system=s.get('system',''); symptom=s.get('name','')
        for c in s.get('cause_details',[]):
            upd=choose(system,symptom,c.get('name',''),c)
            c.update(upd)
            # old 'needs_review' meant numeric/procedure incompleteness; keep source uncertainty but do not hide field method.
            c['field_review_note'] = ('OEM 전용 수치/분해한계 미연결: 현장 격리/비교로 판정하고 임의 수치를 사용하지 않음' if c.get('needs_review') else '')
            changed += 1; bysys[system]+=1

    add_brake_graph(db)
    db['diagnostic_normalization']={
        'version':'1.0-field-executable',
        'cause_count':changed,
        'strategy':'manual evidence -> pre-disassembly check -> isolation/comparison -> measurement -> confirm -> disassembly gate',
        'required_fields':['diag_plan','field_tools','field_rule_out','field_confirm','disassembly_gate','field_evidence_mode','field_ready'],
        'numeric_rule':'OEM/manual value not present => never invent threshold; use isolation/comparison and mark source limitation',
        'brake_rule':'pedal sink/soft/low-fluid causes must separate external leak, air, master/servo bypass and left/right axle piston seal before teardown'
    }

    add_sym023_graph(tm)
    for sid,g in tm['graphs'].items():
        for nid,n in g.get('nodes',{}).items():
            if n.get('type')=='result':
                augment_tm_result(n)
    tm['version']='0.19-field-executable'
    tm['field_diagnostic_policy']={
        'terminal_required':['field_test','rule_out','confirm_if','disassembly_gate'],
        'no_invented_limits':True,
        'pre_teardown_isolation_required':True
    }

    DB_PATH.write_text(json.dumps(db,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    TM_PATH.write_text(json.dumps(tm,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')

    # Audit
    errors=[]; warnings=[]
    all_causes=[]
    for s in db['symptoms']:
        for c in s['cause_details']:
            all_causes.append((s,c))
            for k in ['diag_plan','field_rule_out','field_confirm']:
                if not c.get(k): errors.append(f"{c['id']}: missing {k}")
            if not c.get('disassembly_gate'): errors.append(f"{c['id']}: missing disassembly_gate")
            if not c.get('field_ready'): errors.append(f"{c['id']}: field_ready false")
            if len(c.get('diag_plan',[]))<3: warnings.append(f"{c['id']}: short diag_plan")

    result_count=0
    for sid,g in tm['graphs'].items():
        for nid,n in g.get('nodes',{}).items():
            if n.get('type')=='result':
                result_count += 1
                for k in ['field_test','rule_out','confirm_if']:
                    if not n.get(k): errors.append(f"{sid}/{nid}: missing {k}")
                if not n.get('disassembly_gate'): errors.append(f"{sid}/{nid}: missing disassembly_gate")

    lines=['# FIELD DIAGNOSTIC AUDIT','',
           f'- Manual symptoms: **{len(db["symptoms"])}**',
           f'- Cause details upgraded: **{len(all_causes)}**',
           f'- Systems: **{len(set(s["system"] for s in db["symptoms"]))}**',
           f'- Transmission graphs: **{len(tm["graphs"])}**',
           f'- Transmission result terminals upgraded: **{result_count}**',
           f'- Brake field isolation graph: **BRAKE_HYD_ISOLATION**',
           f'- Errors: **{len(errors)}**', f'- Warnings: **{len(warnings)}**','',
           '## Cause coverage by system','']
    for k,v in sorted(bysys.items()): lines.append(f'- {k}: {v}')
    lines += ['', '## Enforcement',
              '- Every cause has a field sequence, rule-outs, confirmation conditions and a teardown gate.',
              '- Transmission terminal results cannot be accepted as complete with only `action` text.',
              '- OEM numeric limits are reused only when already in the data/manual; missing limits are not fabricated.',
              '- Brake piston-seal diagnosis requires circuit isolation instead of symptom-name matching.',
              '- D34 engine data remains reference-only and must not be presented as D24 vehicle limits.']
    if errors:
        lines += ['', '## Errors'] + [f'- {x}' for x in errors]
    if warnings:
        lines += ['', '## Warnings'] + [f'- {x}' for x in warnings]
    REPORT.write_text('\n'.join(lines)+'\n',encoding='utf-8')
    print('\n'.join(lines[:40]))
    if errors: raise SystemExit(1)

if __name__=='__main__': main()
