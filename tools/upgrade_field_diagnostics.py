    name=cause
    diag=c.get('diag_type','')

    # Universal first principle: reproduce safely and localize before teardown.
    steps.append(f"'{symptom}' 증상을 안전하게 재현하고, {name}이 실제로 증상과 동시에 나타나는지 확인한다.")

